const {chromium} = require(process.env.NARA_PLAYWRIGHT || 'playwright');
(async()=>{
  const browser = await chromium.launch({channel:'msedge', headless:true});
  const page = await browser.newPage({viewport:{width:1060,height:720}});
  await page.goto('http://127.0.0.1:3082/live/');
  await page.locator('form button:enabled').waitFor();
  await page.selectOption('#mode','rules_only');
  await page.click('button');
  await page.getByText('Rules Only · 模型调用 0 次').waitFor();
  await page.locator('#results details').nth(1).locator('summary').click();
  await page.locator('#results details').nth(1).locator('pre').evaluate(node=>node.style.maxHeight='190px');
  await page.screenshot({path:'assets/c01.png'});
  await page.goto('http://127.0.0.1:3082/replay/');
  await page.locator('#cases option').first().waitFor({state:'attached'});
  await page.selectOption('#cases','C07');
  await page.getByText('预期 reject，实际 grant',{exact:false}).first().waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:process.env.TEMP+'/nara-replay-mobile.png'});
  await page.goto('http://127.0.0.1:3082/film/');
  await page.waitForFunction(()=>document.querySelector('video').readyState >= 1);
  console.log('Video duration:', await page.locator('video').evaluate(video=>video.duration));
  await browser.close();
})().catch(error=>{console.error(error.message);process.exit(1)});
